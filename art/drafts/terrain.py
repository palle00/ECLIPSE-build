def sandstone_wall(v, name, n):
    """Layered sandstone cliffs: wavy strata (the same in every variant, so cliffs join), eroded pockets per variant."""
    cv = Canvas(n, n, "d8b88f", var=v)
    st = seeded(name, 77)
    layers = [(R(st, 0, 8) + k * 8, R(st, 0, 6), R(st, .9, 1.5)) for k in range(4)]
    for rep in range(n // 32):
        for (y, ph, amp) in layers:
            y += rep * 32
            cv.paint(wavy(0, y, n, y, 2.5, amp, n // 32, ph, steps=8 * n // 32), "f2dfc2")
            cv.paint(wavy(0, y + 4.4, n, y + 4.4, .7, amp, n // 32, ph + .5, steps=8 * n // 32), "b8956c")
    def pocket(cv, x, y, rnd):
        cv.paint(blob(x + .6, y + .6, R(rnd, 1.2, 2), rnd, .3), "a8845e")
        cv.paint(blob(x, y, R(rnd, 1, 1.8), rnd, .3), "fbecd6")
    scatter(cv, name, "pockets", 3, 3.5, pocket)
    return cv

