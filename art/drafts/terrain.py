"""Terrain of the three ECLIPSE planets (floors, cliff walls, trees, boulders) -> art/pixel-terrain letter grids, rendered by
tools/PixelArt.java into assets/sprites/blocks/environment (floors must share the environment texture page).

Usage: python -I terrain.py OUT_DIR [name ...]
- Land floors: 32x32, 3 variants (NAME1-3) + NAME (variant 1 with the centre pixel on the base tone: the game takes a
  block's map / planet colour from the centre pixel of its icon). Like vanilla floors, every shape stays inside its tile,
  so any two variants sit side by side without seams. Edges between different floors are generated by the game.
- Liquid floors: one 32x32 tile (NAME) that wraps, like vanilla water; the game's water shader moves it. The shallow
  blends (liquid over sand) are generated by the game (ShallowLiquid).
- Cliff walls: 32x32, 2 variants + NAME-large (64x64, drawn over 2x2 of the same wall). Shapes that touch a tile edge
  are shared by all variants (terrainlib.scatter / voronoi), so wall masses join without seams.
- Trees 48x48 (StaticTree), boulders 32x32 with 2 variants (Prop)."""
import sys, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from terrainlib import *

R = lambda rnd, a, b: rnd.uniform(a, b)
N = 32

def land(base): return Canvas(N, N, base, wrap=False)
def water(base): return Canvas(N, N, base, wrap=True)

def bands(cv, rnd, col, k, w, amp, waves=1):
    """Full-width swells that repeat across tiles (liquids): the same height at both ends, whole waves only."""
    for i in range(k):
        y = (i + R(rnd, .2, .8)) * N / k
        cv.paint(wavy(0, y, N, y, w, amp, waves, R(rnd, 0, 6), steps=16), col)

