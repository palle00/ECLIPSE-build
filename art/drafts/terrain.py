def main():
    out = sys.argv[1]; only = set(sys.argv[2:])
    os.makedirs(out, exist_ok=True)
    want = lambda name: not only or name in only
    for name, (f, base) in FLOORS.items():
        if not want(name): continue
        for v in range(3):
            px = quantize(f(v, seeded(name, v)).pixels())
            write(out, f"{name}{v + 1}", px)
            if v == 0:
                px[16][16] = base
                write(out, name, px)
        print("floor", name)
    for name, (f, base) in LIQUIDS.items():
        if not want(name): continue
        px = quantize(f(seeded(name, 0)).pixels())
        px[16][16] = base
        write(out, name, px)
        print("liquid", name)
    for name, (f, base) in WALLS.items():
        if not want(name): continue
        for v in range(2):
            px = quantize(f(v, name, 32).pixels())
            write(out, f"{name}{v + 1}", px)
            if v == 0:
                px[16][16] = base
                write(out, name, px)
        write(out, name + "-large", quantize(f(0, name, 64).pixels()))
        print("wall", name)
    for name, f in TREES.items():
        if want(name):
            write(out, name, quantize(f(seeded(name, 0)).pixels(.5))); print("tree", name)
    for name, f in BOULDERS.items():
        if not want(name): continue
        for v in range(2): write(out, f"{name}{v + 1}", quantize(f(v, seeded(name, v)).pixels(.5)))
        write(out, name, quantize(f(0, seeded(name, 0)).pixels(.5)))
        print("boulder", name)

if __name__ == "__main__":
    main()
