def slag_wall(v, name, n):
    """Slag cliffs: dark slag lumps lit top-left, black glassy spots."""
    cv = Canvas(n, n, "3a302e", var=v)
    def lump(cv, x, y, rnd):
        r = R(rnd, 3.2, 4.4)
        cv.paint(blob(x + 1, y + 1, r, rnd, .3, lobes=4), "211a19")
        cv.paint(blob(x, y, r, rnd, .3, lobes=4), "4c3f3a")
        cv.paint(blob(x - r * .4, y - r * .4, r * .4, rnd, .3), "6a5850")
    def glass(cv, x, y, rnd):
        cv.paint(blob(x, y, R(rnd, 1.2, 1.8), rnd, .3), "1a1414")
        cv.paint(circle(x - .5, y - .5, .55), "7a6a66")
    scatter(cv, name, "lumps", 11, 7, lump)
    scatter(cv, name, "glass", 3, 3, glass)
    return cv

def scrap_wall(v, name, n):
    """A heap of wreckage: tilted steel plates and rusted girders, lit on their upper edges."""
    cv = Canvas(n, n, "2e2f35", var=v)
    def piece(cv, x, y, rnd):
        a = math.radians(R(rnd, 0, 180))
        top, mid, dark = rnd.choice([("8f939e", "666a74", "40424a"), ("b0764a", "85553a", "54382a"), ("7a7e88", "5a5e68", "3a3c44")])
        L, W = R(rnd, 3.5, 5.2), R(rnd, 1.6, 2.6)
        p = poly([(x + math.cos(a) * L * sx - math.sin(a) * W * sy, y + math.sin(a) * L * sx + math.cos(a) * W * sy) for (sx, sy) in ((-1, -1), (1, -1), (1, 1), (-1, 1))])
        cv.paint(shifted(p, 1.2, 1.2), "1e1f24")
        cv.paint(p, mid)
        cv.paint(minus(p, shifted(p, -1.1, -1.1)), dark)
        cv.paint(minus(p, shifted(p, 1.1, 1.1)), top)
    scatter(cv, name, "pieces", 18, 7.5, piece)
    return cv

def scrap(v, rnd, n=32):
    """A chunk of wreckage: a bent, rust-eaten plate (variant 1) or a girder end (variant 2)."""
    cv = Canvas(n, n, None, wrap=False)
    c = n / 2
    if v == 0:
        p = poly([(c - 12, c - 5), (c - 2, c - 11), (c + 11, c - 7), (c + 13, c + 4), (c + 4, c + 11), (c - 10, c + 8)])
        cv.paint(shifted(p, 1.5, 1.5), "1e1f24")
        cv.paint(p, "62666f")
        cv.paint(clip(poly([(c - 14, c - 14), (c + 14, c - 14), (c - 14, c + 5)]), p), "838792")
        cv.paint(clip(blob(c + 5, c + 4, 5.5, rnd, .4), p), "8a5638")
        cv.paint(capsule(c - 7, c + 2, c + 7, c - 5, .7), "3c3e46")
    else:
        beam = poly([(c - 13, c - 3), (c + 13, c - 9), (c + 14, c - 2), (c - 12, c + 4)])
        cv.paint(shifted(beam, 1.5, 1.5), "1e1f24")
        cv.paint(beam, "85553a")
        cv.paint(clip(shifted(beam, 0, -2.2), beam), "b0764a")
        cv.paint(capsule(c - 11, c + 1.5, c + 12, c - 4.5, .8), "54382a")
        for k in (-7, 0, 7): cv.paint(circle(c + k, c - 2.5 - k * .23, 1), "d0a070")
    return cv

